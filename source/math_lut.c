void math_init(void) {
    // LUT is static
}

int fixed_sin(int angle) {
    return s_sin_lut[angle & 0xFF];
}

int fixed_cos(int angle) {
    return s_sin_lut[(angle + 64) & 0xFF];
}

int fixed_atan2(int dy, int dx) {
    if (dx == 0 && dy == 0) return 0;
    
    int abs_x = (dx < 0) ? -dx : dx;
    int abs_y = (dy < 0) ? -dy : dy;
    int sum = abs_x + abs_y;
    if (sum == 0) return 0;

    int ratio = (abs_y * 64) / sum;
    int angle = 0;

    if (dx >= 0 && dy >= 0) {
        angle = ratio;
    } else if (dx < 0 && dy >= 0) {
        angle = 128 - ratio;
    } else if (dx < 0 && dy < 0) {
        angle = 128 + ratio;
    } else {
        angle = 256 - ratio;
    }

    return angle & 0xFF;
}
